/** The CSS a theme contract compiles to. Shared by the build script and the tests. */
export const THEME_VAR = {
  bg: '--ui-bg',
  surface: '--ui-surface',
  surface2: '--ui-surface-2',
  ink: '--ui-ink',
  inkSoft: '--ui-ink-soft',
  inkFaint: '--ui-ink-faint',
  inkMuted: '--ui-ink-muted',
  line: '--ui-line',
  accent: '--ui-accent',
  danger: '--ui-danger',
  warning: '--ui-warning',
  success: '--ui-success',
  info: '--ui-info',
};

function block(selector, palette, mode) {
  const lines = Object.entries(THEME_VAR).map(([key, variable]) => `  ${variable}: ${palette[key]};`);
  return `${selector} {\n  color-scheme: ${mode};\n${lines.join('\n')}\n}\n`;
}

/** The complete themes.css for the given palettes. */
export function renderThemesCss(themes, modes) {
  const parts = [
    '/* Generated by scripts/build-themes.js from src/themes.js. Do not edit by hand. */',
    '',
    block(':root', themes.gruvbox.light, 'light'),
    block(':root[data-mode="dark"]:not([data-theme])', themes.gruvbox.dark, 'dark'),
  ];

  for (const [id, theme] of Object.entries(themes)) {
    for (const mode of modes) {
      parts.push(block(`[data-theme="${id}"][data-mode="${mode}"]`, theme[mode], mode));
    }
  }

  return parts.join('\n');
}
